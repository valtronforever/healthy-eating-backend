"""Build `tokens.css` for the chat cards from the iOS app's design tokens.

The iOS repository's `design/system/tokens.json` is the source of every color, type style,
spacing value and radius. This module turns it into CSS custom properties (light and dark),
so the cards shown in the chat (MCP Apps) look like the app. The output is committed; the
backend never reads the iOS repository at runtime.

    uv run python -m healthy_eating.mcp_server.ui.build_tokens <tokens.json>
    uv run python -m healthy_eating.mcp_server.ui.build_tokens --check <tokens.json>
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

OUTPUT = Path(__file__).parent / "tokens.css"

HEADER = (
    "/* Generated by healthy_eating.mcp_server.ui.build_tokens from the iOS app's\n"
    "   design/system/tokens.json. Do not edit by hand. */\n"
)


def _color_lines(tokens: list[dict[str, Any]], theme: str) -> list[str]:
    values = {token["name"]: token["value"] for token in tokens}
    lines = []
    for name, value in values.items():
        # A token may point at another one ("link": "{accent}").
        if isinstance(value, str) and value.startswith("{") and value.endswith("}"):
            lines.append(f"  --he-{name}: var(--he-{value[1:-1]});")
        else:
            lines.append(f"  --he-{name}: {value[theme]};")
    return lines


def build_css(tokens: dict[str, Any]) -> str:
    colors = tokens["color"]["tokens"]
    families = tokens["type"]["families"]
    # No `color-scheme`: an iframe whose scheme differs from the host page's gets an opaque
    # canvas, and the card must stay transparent around its own surface.
    root = [f"  --he-font-{name}: {stack};" for name, stack in families.items()]
    root += [f"  --he-{t['name']}: {t['value']};" for t in tokens["spacing"]["tokens"]]
    root += [f"  --he-{t['name']}: {t['value']};" for t in tokens["radius"]["tokens"]]
    root += _color_lines(colors, "light")
    dark = _color_lines(colors, "dark")

    parts = [HEADER]
    parts.append(":root {\n" + "\n".join(root) + "\n}\n")
    # The host's theme wins (data-theme set by the card); otherwise follow the system.
    parts.append(":root[data-theme='dark'] {\n" + "\n".join(dark) + "\n}\n")
    parts.append(
        "@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n"
        + "\n".join("  " + line for line in dark)
        + "\n  }\n}\n"
    )
    for group in tokens["type"]["groups"]:
        family = group["family"]
        for style in group["styles"]:
            declarations = [
                f"font-family: var(--he-font-{family})",
                f"font-size: {style['fontSize']}",
                f"line-height: {style['lineHeight']}",
                f"font-weight: {style['fontWeight']}",
            ]
            if "letterSpacing" in style:
                declarations.append(f"letter-spacing: {style['letterSpacing']}")
            if family == "rounded":
                declarations.append("font-variant-numeric: tabular-nums")
            parts.append(f".he-{style['name']} {{ {'; '.join(declarations)}; }}\n")
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("tokens", type=Path, help="The iOS repo's design/system/tokens.json")
    parser.add_argument("--check", action="store_true", help="Fail if tokens.css is out of date")
    args = parser.parse_args(argv)
    css = build_css(json.loads(args.tokens.read_text(encoding="utf-8")))
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != css:
            print(f"{OUTPUT} is out of date; run without --check", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(css, encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
